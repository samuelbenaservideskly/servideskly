/**
 * Forward-only schema migrations, recorded in `schema_migrations`.
 *
 * Rules:
 *  - never edit a migration that has shipped, append a new one instead;
 *  - each entry runs inside a single transaction together with the row that
 *    records it, so a failure leaves neither half applied.
 *
 * SQLite conventions used throughout, and relied on by src/db/index.ts:
 *  - timestamps are TEXT, ISO-8601 UTC with milliseconds, so they sort
 *    correctly as text;
 *  - booleans are INTEGER 0/1, converted at the data layer;
 *  - JSON documents are TEXT, parsed at the data layer;
 *  - identifiers are uuid TEXT, generated by the application.
 */
export interface Migration {
  readonly version: number;
  readonly name: string;
  /** SQLite. */
  readonly sql: string;
  /**
   * PostgreSQL, for a migration after PG_BASELINE_VERSION (src/db/pg-schema.ts).
   * Earlier ones are covered by the baseline; a later one without this
   * refuses to run on PostgreSQL rather than guess.
   */
  readonly pg?: string;
}

/** Matches `sqlNow` in src/db/index.ts. Inlined because DDL cannot bind. */
