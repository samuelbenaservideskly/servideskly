/**
 * Writes src/db/pg-schema.ts: the PostgreSQL schema, translated from the
 * schema SQLite ends up with after every migration.
 *
 *   npx tsx scripts/pg-schema.ts
 *
 * Run it after adding a migration, and give that migration a `pg` variant
 * for databases already past the baseline. tests/pg-schema.test.ts fails
 * when the two schemas drift apart.
 *
 * Translation, deliberately small because the schema is plain:
 *  - INTEGER -> BIGINT (SQLite integers are 64-bit; pg returns them as
 *    numbers through a type parser in src/db/index.ts);
 *  - the "now" default -> the same text format from PostgreSQL;
 *  - json_extract(col, '$.a') in an index -> (col::jsonb ->> 'a');
 *  - comments dropped; tables ordered so every REFERENCES target exists.
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'pg-schema-'));
process.env.DATABASE_PATH = path.join(dir, 'schema.sqlite');
process.env.DATABASE_URL = '';
process.env.APP_BASE_URL = 'http://localhost:3000';
process.env.NODE_ENV = 'test';
process.env.LOG_LEVEL = 'silent';
process.env.SESSION_SECRET = 'schema-generator-'.repeat(3);

const { sqliteHandle, runMigrations, closeDatabase } = await import('../src/db/index.js');
const { migrations, PG_NOW } = await import('../src/db/migrations.js');
await runMigrations();

const SQLITE_NOW = /strftime\('%Y-%m-%dT%H:%M:%fZ', 'now'\)/g;

function translate(sql: string): string {
  return sql
    .replace(/--[^\n]*/g, '')
    .replace(SQLITE_NOW, PG_NOW)
    .replace(/\bINTEGER\b/gi, 'BIGINT')
    .replace(/json_extract\((\w+), '\$\.(\w+)'\)/g, "(($1::jsonb) ->> '$2')")
    .replace(/\n\s*\n/g, '\n')
    .trim();
}

const rows = sqliteHandle()
  .prepare("SELECT type, name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' AND name <> 'schema_migrations'")
  .all() as { type: string; name: string; sql: string }[];

// Tables in an order where every referenced table is created first.
const tables = new Map(rows.filter((r) => r.type === 'table').map((r) => [r.name, r.sql]));
const ordered: string[] = [];
const visiting = new Set<string>();
function visit(name: string): void {
  if (ordered.includes(name) || !tables.has(name)) return;
  if (visiting.has(name)) throw new Error('reference cycle at ' + name);
  visiting.add(name);
  for (const [, target] of tables.get(name)!.matchAll(/REFERENCES\s+"?(\w+)"?/gi)) {
    if (target !== name) visit(target!);
  }
  visiting.delete(name);
  ordered.push(name);
}
for (const name of [...tables.keys()].sort()) visit(name);

const statements = [
  ...ordered.map((name) => translate(tables.get(name)!)),
  ...rows.filter((r) => r.type === 'index').sort((a, b) => a.name.localeCompare(b.name)).map((r) => translate(r.sql)),
];
// Rows the migrations themselves insert (built-in dashboards, the settings
// row, seeds): a new PostgreSQL database must start with them too.
const literal = (v: unknown): string =>
  v === null || v === undefined ? 'NULL'
    : typeof v === 'number' || typeof v === 'bigint' ? String(v)
      : "'" + String(v).replace(/'/g, "''") + "'";
let seeded = 0;
for (const name of ordered) {
  const data = sqliteHandle().prepare('SELECT * FROM "' + name + '"').all() as Record<string, unknown>[];
  for (const row of data) {
    const cols = Object.keys(row);
    statements.push('INSERT INTO ' + name + ' (' + cols.join(', ') + ') VALUES (' + cols.map((c) => literal(row[c])).join(', ') + ')');
    seeded += 1;
  }
}

const unknown = rows.filter((r) => r.type !== 'table' && r.type !== 'index');
if (unknown.length > 0) throw new Error('not translated: ' + unknown.map((r) => r.type + ' ' + r.name).join(', '));

const baseline = Math.max(...migrations.map((m) => m.version));
const out = `/**
 * GENERATED by scripts/pg-schema.ts - do not edit by hand.
 *
 * The PostgreSQL schema equal to SQLite's after migration ${baseline}. A new
 * PostgreSQL database is created from this and records migrations 1-${baseline}
 * as applied; later migrations need a \`pg\` variant.
 */
export const PG_BASELINE_VERSION = ${baseline};

export const PG_SCHEMA = ${JSON.stringify(statements.join(';\n\n') + ';\n')};
`;
fs.writeFileSync(path.join(root, 'src/db/pg-schema.ts'), out);
console.log('wrote src/db/pg-schema.ts: ' + ordered.length + ' tables, ' + seeded + ' seeded rows, baseline ' + baseline);
await closeDatabase();
fs.rmSync(dir, { recursive: true, force: true });
